package top.yztz.msggo.services;

import android.content.BroadcastReceiver;
import android.content.Context;
import android.content.Intent;
import android.os.Bundle;
import android.telephony.SmsMessage;
import android.util.Log;

public class SMSResponseReceiver extends BroadcastReceiver {
    private static final String TAG = "SMSResponseReceiver";

    public interface Callback {
        void onResponseReceived(String phoneNumber);
    }

    private final Callback callback;

    public SMSResponseReceiver(Callback callback) {
        this.callback = callback;
    }

    @Override
    public void onReceive(Context context, Intent intent) {
        if (!"android.provider.Telephony.SMS_RECEIVED".equals(intent.getAction())) {
            return;
        }

        Bundle bundle = intent.getExtras();
        if (bundle == null) return;

        Object[] pdus = (Object[]) bundle.get("pdus");
        String format = bundle.getString("format");
        if (pdus == null) return;

        for (Object pdu : pdus) {
            SmsMessage smsMessage;
            if (android.os.Build.VERSION.SDK_INT >= android.os.Build.VERSION_CODES.M) {
                smsMessage = SmsMessage.createFromPdu((byte[]) pdu, format);
            } else {
                smsMessage = SmsMessage.createFromPdu((byte[]) pdu);
            }
            String sender = smsMessage.getDisplayOriginatingAddress();
            Log.d(TAG, "SMS received from: " + sender);
            
            if (callback != null && sender != null) {
                callback.onResponseReceived(sender);
            }
        }
    }
}
